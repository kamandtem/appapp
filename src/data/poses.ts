function normalizePoseTitle(value: string): string {
  return value.toLowerCase().replace(/[‌‌‏]/g, ' ').replace(/[^آ-یa-z0-9 ]/g, ' ').replace(/\s+/g, ' ').trim();
}
function titleSimilarity(a: string, b: string): number {
  const aa = new Set(normalizePoseTitle(a).split(' ').filter(Boolean));
  const bb = new Set(normalizePoseTitle(b).split(' ').filter(Boolean));
  if (!aa.size || !bb.size) return 0;
  let common = 0; aa.forEach((x) => { if (bb.has(x)) common++; });
  return common / Math.min(aa.size, bb.size);
}
/** حذف تکراری‌های واقعاً مشابه، با اولویت ژست‌های اصلی برنامه. */
export function dedupePoses(list: Pose[]): Pose[] {
  const out: Pose[] = [];
  for (const pose of list) {
    const duplicate = out.some((existing) => normalizePoseTitle(existing.title) === normalizePoseTitle(pose.title) || titleSimilarity(existing.title, pose.title) >= 0.78);
    if (!duplicate) out.push(pose);
  }
  return out;
}

/**
 * پوشه‌ی یکپارچه‌ی عکس مرجع همه‌ی ژست‌ها. دیگر از طرح SVG یا از پوشه‌های
 * قدیمی (poses/ و reference/) استفاده نمی‌شود؛ هر ژست دقیقاً یک فایل با
 * شماره‌ی ثابت در همین پوشه دارد. تا وقتی عکس واقعی جایگزین نشده، یک
 * تصویر جای‌گیرنده (placeholder) با همان شماره نمایش داده می‌شود.
 */
export const PHOTO_FOLDER = '/generated/photos';

function assignCanonicalPhotos(list: Pose[]): Pose[] {
  return list.map((pose, i) => ({
    ...pose,
    image: `${PHOTO_FOLDER}/pose-${String(i + 1).padStart(3, '0')}.webp`,
  }));
}

/** تعداد ژست‌های اصلی که همیشه و کامل نگه داشته می‌شوند */
export const CORE_POSE_COUNT = 40;

/**
 * «کمی شبیه» یعنی عنوان‌ها به هم نزدیک باشند، یا هر سه‌ی دسته‌بندی، نوع ژست و
 * فرم صحنه یکی باشد. در این حالت ژست تکراری محسوب می‌شود.
 */
function nearlySamePose(a: Pose, b: Pose): boolean {
  if (titleSimilarity(a.title, b.title) >= 0.4) return true;
  return a.category === b.category && a.poseType === b.poseType && a.art === b.art;
}

/**
 * ۴۰ ژست اول دست‌نخورده می‌مانند. از بقیه، هر ژستی که کمی شبیه یکی از آن ۴۰
 * ژست باشد حذف می‌شود و فقط ژست‌های واقعاً متفاوت باقی می‌مانند.
 */
function keepCoreAndDistinct(list: Pose[]): Pose[] {
  const core = list.slice(0, CORE_POSE_COUNT);
  const distinct = list
    .slice(CORE_POSE_COUNT)
    .filter((pose) => !core.some((c) => nearlySamePose(c, pose)));
  return [...core, ...distinct];
}

