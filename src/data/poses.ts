/** تشخیص تصویرسازی مناسب از روی متن (برای ژست‌های خود کاربر هم استفاده می‌شود) */
export function artForText(text: string, fallback: ArtKey): ArtKey {
  for (const [re, key] of ART_RULES) {
    if (re.test(text)) return key;
  }
  return fallback;
}

function resolveArt(s: Seed): ArtKey {
  const hay = [s.t, s.tags.join(' '), s.steps.join(' ')].join(' ');
  for (const [re, key] of ART_RULES) {
    if (re.test(hay)) return key;
  }
  if (s.c === 'عروس' && s.n === 1) return 'soloBride';
  if (s.c === 'داماد' && s.n === 1) return 'soloGroom';
  return s.art;
}

