function stageFor(ease: number): ComfortStage {
  if (ease <= 2) return 'یخ‌شکن';
  if (ease <= 5) return 'گرم شدن';
  if (ease <= 8) return 'نزدیک شدن';
  if (ease <= 11) return 'صمیمی';
  return 'حرفه‌ای';
}

export function easeOf(difficulty: DifficultyLevel, art: ArtKey, peopleCount: number): number {
  const intimacy = ART_INTIMACY[art];
  return DIFF_RANK[difficulty] + (typeof intimacy === 'number' ? intimacy : 2) + (peopleCount > 2 ? 1 : 0);
}

/** امتیاز و برچسب مرحله را با هم برمی‌گرداند */
export function progressionMeta(
  difficulty: DifficultyLevel,
  art: ArtKey,
  peopleCount: number
): { ease: number; stage: ComfortStage } {
  const ease = easeOf(difficulty, art, peopleCount);
  return { ease, stage: stageFor(ease) };
}

/** ژست‌ها را از ساده‌ترین (یخ‌شکن) به سخت‌ترین مرتب می‌کند */
export function sortForProgression(list: Pose[]): Pose[] {
  return [...list].sort((a, b) => a.ease - b.ease);
}

export function build(s: Seed, i: number): Pose {
  const d = { ...BASE, ...(BY_TYPE[s.p] || {}) };
  const art = resolveArt(s);
  const ease = easeOf(s.d, art, s.n);
  return {
    id: `pose-${String(i + 1).padStart(3, '0')}`,
    title: s.t,
    ease,
    stage: stageFor(ease),
    suggestedMinutes: s.suggestedMinutes,
    category: s.c,
    poseType: s.p,
    difficulty: s.d,
    peopleCount: s.n,
    locations: s.loc,
    gardenSubCategory: s.loc.includes('باغ عمارت') ? s.gsc : undefined,
    art,
    image: s.image,
    tags: [...s.tags, s.p, ...s.loc],
    steps: s.steps,
    bodyPosition: s.body || d.body,
    handPosition: s.hand || d.hand,
    footPosition: s.foot || d.foot,
    headDirection: s.head || d.head,
    eyeDirection: s.eye || d.eye,
    photographerScript: s.say,
    commonMistakes: s.miss,
    variations: s.vary,
    cameraTips: {
      framing: s.frame || d.frame,
      cameraAngle: s.angle || d.angle,
      suggestedDistance: s.dist || d.dist,
      lensSuggestion: s.lens || d.lens,
      lightTip: s.light || d.light,
    },
  };
}

